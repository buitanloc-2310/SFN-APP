import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';

const root=path.resolve(path.dirname(new URL(import.meta.url).pathname),'..');
const required=[
  'src/index.js','src/auth.js','src/public.js','src/admin.js','src/me.js','src/utils.js','src/email.js','src/permissions.js',
  'public/index.html','public/bootstrap.js','public/digital-portal.js','public/app.js','public/styles.css','public/digital.css','public/sw.js','public/manifest.webmanifest',
  'public/email-template.html',
  'public/email-templates/email_universal_auto.html',
  'public/email-templates/application-received.html',
  'public/email-templates/registration-confirmation.html',
  'public/email-templates/certificate-issued.html',
  'public/email-templates/application-status-updated.html',
  'public/email-templates/information-required.html',
  'public/email-templates/application-result.html',
  'public/email-templates/account-notification.html',
  'public/email-templates/support-ticket-received.html',
  'public/email-templates/fundraising-update.html',
  'migrations/0001_schema.sql','migrations/0002_seed.sql','migrations/0005_digital_information_infrastructure.sql',
  'migrations/0008_sky_first_digital_information_system.sql','migrations/0009_super_website_universal_email_and_cms.sql',
  'migrations/0010_forensic_security_and_financial_reconciliation.sql','migrations/0011_v10_admin_cms_i18n_governance.sql','wrangler.jsonc'
];
let ok=true;
for(const f of required){
  if(!fs.existsSync(path.join(root,f))){console.error('MISSING',f);ok=false;}
}
for(const f of [...fs.readdirSync(path.join(root,'src')).filter(x=>x.endsWith('.js')).map(x=>'src/'+x),'public/bootstrap.js','public/digital-portal.js','public/app.js','public/sw.js']){
  const r=spawnSync(process.execPath,['--check',path.join(root,f)],{encoding:'utf8'});
  if(r.status!==0){console.error('JS SYNTAX FAIL',f,r.stderr);ok=false;}
}
const publicText=['public/index.html','public/bootstrap.js','public/digital-portal.js','public/app.js','public/styles.css','public/digital.css'].map(f=>fs.readFileSync(path.join(root,f),'utf8')).join('\n');
for(const bad of [
  'Enhanced V2','bản xem trước','mô phỏng Dashboard','test password','Generated by AI','AI generated','Lorem ipsum','hotro@skyfirst.io.v',
  'Lưu ý pháp lý về chữ ký trong biểu mẫu','không phải chữ ký số được chứng thực pháp lý'
]){
  if(publicText.toLowerCase().includes(bad.toLowerCase())){console.error('FORBIDDEN PUBLIC TEXT FOUND:',bad);ok=false;}
}
const indexHtml=fs.readFileSync(path.join(root,'public/index.html'),'utf8');
if(!indexHtml.includes('Hệ thống Thông tin Số Sky First') || !indexHtml.includes('app.skyfirst.io.vn')){
  console.error('IDENTITY CHECK FAILED in public/index.html');
  ok=false;
}
const universalHtml=fs.readFileSync(path.join(root,'public/email-templates/email_universal_auto.html'),'utf8');
for(const token of ['{{PREHEADER}}','{{EMAIL_CATEGORY}}','{{EMAIL_HEADING}}','{{RECIPIENT_NAME}}','{{INTRO_TEXT}}','{{REQUEST_ID}}','{{REGISTRATION_TYPE}}','{{SUBMITTED_AT}}','{{STATUS}}','{{ADDITIONAL_INFO}}','{{BODY_HTML}}','{{NEXT_STEPS}}','{{ACTION_URL}}','{{ACTION_LABEL}}']){
  if(!universalHtml.includes(token)){
    console.error('MISSING UNIVERSAL EMAIL TOKEN in email_universal_auto.html:',token);
    ok=false;
  }
}
if(ok){
  console.log('Sky First Digital Information System V10 Super Website (app.skyfirst.io.vn) validation: OK');
  process.exit(0);
}
process.exit(1);
